const fs = require('node:fs')
const path = require('node:path')
const { execFileSync } = require('node:child_process')
const root = path.resolve(__dirname, '..')
const options = { cwd: root, encoding: 'utf8', windowsHide: true }
const listing = process.platform === 'win32'
  ? execFileSync(process.env.ComSpec || 'cmd.exe', ['/d', '/s', '/c', 'npm ls --omit=dev --all --parseable'], options)
  : execFileSync('npm', ['ls', '--omit=dev', '--all', '--parseable'], options)
const directories = new Set(listing.trim().split(/\r?\n/).filter(dir => path.resolve(dir) !== root))
directories.add(path.join(root, 'node_modules', 'electron'))
const packages = new Map()
const licenseName = /^(licen[sc]e|copying|notice)([._-].*)?$/i
for (const directory of directories) {
  const pkg = JSON.parse(fs.readFileSync(path.join(directory, 'package.json'), 'utf8'))
  const key = pkg.name + '@' + pkg.version
  if (packages.has(key)) continue
  const licenses = []
  const collect = (dir, nested = false) => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, entry.name)
      if (entry.isFile() && licenseName.test(entry.name)) licenses.push({
        file: path.relative(directory, full).replace(/\\/g, '/'), text: fs.readFileSync(full, 'utf8').trim()
      })
      else if (nested && entry.isDirectory() && entry.name !== 'node_modules') collect(full, true)
    }
  }
  collect(directory, pkg.name === 'node-pty')
  if (!licenses.length) throw new Error('Missing upstream license file: ' + key)
  packages.set(key, { key, license: typeof pkg.license === 'string' ? pkg.license : JSON.stringify(pkg.license), licenses })
}
const sections = [
  '# Third-party notices', '',
  'Generated by `node scripts/generate-third-party-notices.cjs` from the installed production dependency tree and Electron.',
  'These components retain their respective licenses and copyrights. This list may include build-bundled dependencies.',
  'Electron also distributes `LICENSE.electron.txt` and `LICENSES.chromium.html`; retain these files with binary distributions.', ''
]
for (const item of [...packages.values()].sort((a, b) => a.key < b.key ? -1 : a.key > b.key ? 1 : 0)) {
  sections.push('## ' + item.key, '', 'Declared license: ' + item.license, '')
  for (const license of item.licenses) sections.push('### ' + license.file, '', '```text', license.text, '```', '')
}
fs.writeFileSync(path.join(root, 'THIRD_PARTY_NOTICES.md'), sections.join('\n'))
console.log(JSON.stringify({ packages: packages.size, file: 'THIRD_PARTY_NOTICES.md' }))
